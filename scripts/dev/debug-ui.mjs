import { chromium } from "playwright-core";
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 375, height: 812 } });
page.on("console", (m) => console.log("console:", m.type(), m.text()));
page.on("pageerror", (e) => console.log("pageerror:", e.message));
page.on("response", (r) => { if (r.url().includes("/api/") || r.url().includes("/samples/")) console.log("resp:", r.status(), r.url()); });
await page.goto("http://localhost:3000", { waitUntil: "networkidle" });
const btns = await page.getByRole("button").allInnerTexts();
console.log("buttons:", btns.map((b) => b.replace(/\n/g, " / ")));
await page.getByRole("button", { name: /Arlington 1-bedroom/ }).click();
await page.waitForTimeout(4000);
console.log("headings:", await page.getByRole("heading").allInnerTexts());
console.log("alerts:", await page.getByRole("alert").allInnerTexts());
await browser.close();
